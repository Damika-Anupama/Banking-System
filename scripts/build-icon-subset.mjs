/**
 * Builds a self-hosted, subsetted Font Awesome from the icons this app actually uses.
 *
 * The app pulled a 92kB stylesheet and a 120kB icon font from a CDN in order to
 * render 165 icons out of the ~2000 the font contains. Everything after the
 * first few kilobytes was bytes the user downloaded and never saw.
 *
 * Subsetting rather than migrating to the SVG components is a deliberate choice:
 * 25 of the icon usages are bound dynamically (`[class]="'fas ' + item.icon"`,
 * the sort arrows, the deposit method icons), and those cannot be rewritten into
 * static <fa-icon> components without inventing a runtime name->icon registry.
 * Subsetting keeps all 535 usages working exactly as they are.
 *
 * Run: node scripts/build-icon-subset.mjs
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync, mkdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const FA = 'node_modules/@fortawesome/fontawesome-free';
const OUT = 'src/assets/icons';

/** Every .html and .ts file that could name an icon. */
function sourceFiles(dir, acc = []) {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) sourceFiles(path, acc);
    else if (/\.(html|ts)$/.test(entry) && !entry.endsWith('.spec.ts')) acc.push(path);
  }
  return acc;
}

// 1. Which icons does the app name? Include .ts, because several are picked at
//    runtime from strings the templates never spell out.
const used = new Set();
for (const file of sourceFiles('src/app')) {
  const text = readFileSync(file, 'utf8');
  for (const m of text.matchAll(/\bfa-([a-z0-9-]+)\b/g)) used.add(`fa-${m[1]}`);
}

// 2. Codepoint for each icon name, read from Font Awesome's own stylesheet.
//    FA6 declares them as a custom property on grouped selectors, e.g.
//    .fa-home-lg,.fa-house-chimney{--fa:"\\e3af"} — not as :before{content:...}.
const css = readFileSync(join(FA, 'css/all.min.css'), 'utf8');
const codepoints = new Map();
//    A handful are plain ASCII characters rather than private-use codepoints
//    (fa-percent is literally "\%", fa-hashtag is "\#"), so both forms are read.
for (const m of css.matchAll(/((?:\.fa-[a-z0-9-]+,?)+)\{--fa:"\\(.+?)"\}/g)) {
  const raw = m[2];
  const codepoint = /^[0-9a-f]{2,5}$/i.test(raw)
    ? raw
    : raw.codePointAt(0).toString(16);
  for (const selector of m[1].split(',')) {
    const name = selector.trim();
    if (name.startsWith('.fa-')) codepoints.set(name.slice(1), codepoint);
  }
}

const resolved = [...used].filter((name) => codepoints.has(name)).sort();
const unknown = [...used].filter((name) => !codepoints.has(name) && !/^fa-(solid|regular|brands|fw|spin|lg|[0-9]x)$/.test(name));

console.log(`icons referenced: ${used.size}, resolved to glyphs: ${resolved.length}`);
if (unknown.length) console.log('  not real icons (ignored):', unknown.join(', '));

// 3. Subset each family down to the glyphs that survived.
mkdirSync(OUT, { recursive: true });
const families = [
  { file: 'fa-solid-900', weight: 900, family: '"Font Awesome 6 Free"' },
  { file: 'fa-regular-400', weight: 400, family: '"Font Awesome 6 Free"' },
];

const unicodes = resolved.map((name) => `U+${codepoints.get(name)}`).join(',');

for (const { file } of families) {
  execFileSync('pyftsubset', [
    join(FA, `webfonts/${file}.woff2`),
    `--unicodes=${unicodes}`,
    '--flavor=woff2',
    '--layout-features=*',
    `--output-file=${join(OUT, `${file}.woff2`)}`,
  ]);
  const before = statSync(join(FA, `webfonts/${file}.woff2`)).size;
  const after = statSync(join(OUT, `${file}.woff2`)).size;
  console.log(`  ${file}.woff2: ${(before / 1024).toFixed(0)}kB -> ${(after / 1024).toFixed(0)}kB`);
}

// 4. A stylesheet with only the rules this app can actually hit.
const rules = resolved
  .map((name) => `.${name}:before{content:"\\${codepoints.get(name)}"}`)
  .join('\n');

const out = `/* Generated by scripts/build-icon-subset.mjs — do not edit by hand.
   Only the ${resolved.length} icons this app uses, self-hosted. Regenerate after
   adding a new icon:  npm run icons  */
@font-face {
  font-family: "Font Awesome 6 Free";
  font-style: normal;
  font-weight: 900;
  font-display: block;
  src: url("/assets/icons/fa-solid-900.woff2") format("woff2");
}
@font-face {
  font-family: "Font Awesome 6 Free";
  font-style: normal;
  font-weight: 400;
  font-display: block;
  src: url("/assets/icons/fa-regular-400.woff2") format("woff2");
}
.fa, .fas, .far, .fa-solid, .fa-regular {
  -moz-osx-font-smoothing: grayscale;
  -webkit-font-smoothing: antialiased;
  display: var(--fa-display, inline-block);
  font-style: normal;
  font-variant: normal;
  line-height: 1;
  text-rendering: auto;
  font-family: "Font Awesome 6 Free";
}
.fa, .fas, .fa-solid { font-weight: 900; }
.far, .fa-regular { font-weight: 400; }
.fa-fw { text-align: center; width: 1.25em; }
.fa-spin { animation: fa-spin 2s infinite linear; }
.fa-lg { font-size: 1.33333em; line-height: 0.75em; vertical-align: -0.0667em; }
.fa-2x { font-size: 2em; }
.fa-3x { font-size: 3em; }
@keyframes fa-spin { 0% { transform: rotate(0deg); } 100% { transform: rotate(360deg); } }
@media (prefers-reduced-motion: reduce) { .fa-spin { animation-delay: -1ms; animation-duration: 1ms; animation-iteration-count: 1; } }
${rules}
`;

writeFileSync(join(OUT, 'icons.css'), out);
console.log(`  icons.css: ${(Buffer.byteLength(out) / 1024).toFixed(0)}kB (was a 92kB CDN stylesheet)`);
